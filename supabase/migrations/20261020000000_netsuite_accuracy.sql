-- A separate read model; no WMS transaction or source spreadsheet is modified.
create table if not exists public.netsuite (
 id bigint generated by default as identity primary key,
 sku text not null,
 nama_barang text not null default '',
 saldo_awal numeric,
 receipts numeric,
 total_qty_masuk numeric,
 sales numeric,
 total_qty_keluar numeric,
 saldo_akhir numeric,
 report_date date,
 source_row_key text not null unique,
 source_row_number integer not null check(source_row_number>0),
 source_hash text not null,
 synced_at timestamptz not null default now()
);
create index if not exists netsuite_sku_idx on public.netsuite(upper(btrim(sku)));
alter table public.netsuite enable row level security;
revoke all on public.netsuite from public,anon,authenticated;
grant select,insert,update,delete on public.netsuite to service_role;
grant usage,select on sequence public.netsuite_id_seq to service_role;

create or replace function public.inventory_netsuite_accuracy()
returns jsonb language sql stable security invoker set search_path=public,pg_temp as $$
 with sources as (
  select source,status,last_success_at,locked_at,source_version from public.inventory_sync_status where source in ('kartu_stok','netsuite')
 ), readiness as (
  select count(*)=2 and bool_and(status='success' and last_success_at is not null and locked_at is null) as ready from sources
 ), kartu as (
  select upper(btrim(sku)) as key,min(btrim(sku)) as sku,max(nama_barang) as nama,
   case when bool_and(stok_akhir is not null) then sum(stok_akhir) end as stock,
   string_agg(distinct nullif(btrim(lokasi_bulky),''),', ' order by nullif(btrim(lokasi_bulky),'')) as lokasi
  from public.inventory_kartu_stok where nullif(btrim(sku),'') is not null group by upper(btrim(sku))
 ), ns as (
  select upper(btrim(sku)) as key,min(btrim(sku)) as sku,max(nama_barang) as nama,
   case when bool_and(saldo_akhir is not null) then sum(saldo_akhir) end as stock
  from public.netsuite where nullif(btrim(sku),'') is not null group by upper(btrim(sku))
 ), compared as (
  select coalesce(kartu.sku,ns.sku) as sku,coalesce(nullif(kartu.nama,''),ns.nama,'') as nama,
   coalesce(kartu.lokasi,'—') as lokasi_text,kartu.stock as stok_kartu,ns.stock as stok_netsuite,
   case when kartu.stock is not null and ns.stock is not null then kartu.stock-ns.stock end as selisih,
   case when kartu.key is null then 'Kartu Stok belum tersedia' when ns.key is null then 'NetSuite belum tersedia'
    when kartu.stock is null or ns.stock is null then 'Saldo belum lengkap'
    when kartu.stock=ns.stock then 'Akurat' else 'Selisih' end as status
  from kartu full outer join ns using(key)
 )
 select jsonb_build_object('ready',(select ready from readiness),
  'sources',coalesce((select jsonb_agg(to_jsonb(sources) order by source) from sources),'[]'::jsonb),
  'reportDates',coalesce((select jsonb_agg(d order by d) from (select distinct report_date as d from public.netsuite where report_date is not null) reports),'[]'::jsonb),
  'rows',case when (select ready from readiness) then coalesce((select jsonb_agg(to_jsonb(compared) order by sku) from compared),'[]'::jsonb) else '[]'::jsonb end
 );
$$;
revoke all on function public.inventory_netsuite_accuracy() from public,anon,authenticated;
grant execute on function public.inventory_netsuite_accuracy() to service_role;
notify pgrst,'reload schema';

-- Reuse the existing scheduler's endpoint origin and authorization configuration.
-- Its secret stays in the database; it is never returned to the browser or logs.
create or replace function public.dispatch_netsuite_sync()
returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare template text; request_id bigint;
begin
 select command into template from cron.job where active and command like '%/api/sync/inventory/kartu-stok%' order by jobid limit 1;
 if template is null then raise exception 'NETSUITE_SYNC_TEMPLATE_UNAVAILABLE'; end if;
 execute replace(template,'/api/sync/inventory/kartu-stok','/api/sync/inventory/netsuite') into request_id;
 return request_id;
end;
$$;
revoke all on function public.dispatch_netsuite_sync() from public,anon,authenticated;
grant execute on function public.dispatch_netsuite_sync() to service_role;
